#!/usr/bin/env node
/**
 * Generates deployment/_redirects.
 *
 * M11 in the August 2026 audit: CLOUDFLARE_DEPLOYMENT.md claims ".html URLs redirect
 * once to extensionless URLs", but nothing in the repo enforced it. Cloudflare Pages
 * does normalise .html by default, so it probably worked -- but "probably" is not a
 * guarantee, and if it ever regressed the result is duplicate content on ~310 URL
 * pairs, every one of them a self-inflicted canonicalisation problem.
 *
 * Rather than rely on an undocumented wildcard shape, this enumerates one explicit
 * 301 per page. Cloudflare Pages allows 2,000 static redirects; the site needs ~310.
 * Rules in _redirects are evaluated before Pages' own asset resolution, so these win.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'deployment', '_redirects');
const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', '.runtime', 'uploads', 'scripts', 'deployment', 'content']);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.html')) out.push(full);
  }
  return out;
}

function toUrlPath(file) {
  return '/' + path.relative(ROOT, file).split(path.sep).join('/');
}

/** The extensionless URL this .html file is canonically served at. */
function canonicalFor(urlPath) {
  if (urlPath === '/index.html') return '/';
  if (urlPath.endsWith('/index.html')) return urlPath.slice(0, -'index.html'.length);
  return urlPath.slice(0, -'.html'.length);
}

const files = walk(ROOT)
  .map(toUrlPath)
  // 404.html is served as the not-found page, never as a redirect target.
  .filter((urlPath) => urlPath !== '/404.html')
  .sort();

const rules = files.map((urlPath) => {
  const target = canonicalFor(urlPath);
  return `${urlPath}  ${target}  301`;
});

const header = [
  '# Generated by scripts/generate-redirects.js -- do not edit by hand.',
  '# One 301 per page, forcing every .html URL onto its extensionless canonical so',
  '# the two forms can never both be indexed.',
  ''
];

fs.writeFileSync(OUTPUT, header.concat(rules).join('\n') + '\n');

console.log(JSON.stringify({ output: path.relative(ROOT, OUTPUT), redirects: rules.length }, null, 2));
